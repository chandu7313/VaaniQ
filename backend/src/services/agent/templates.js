export function t(lang, key, params = {}) {
  const table = T[lang] || T.en;
  const tpl = table[key] ?? T.en[key];
  if (typeof tpl !== 'string') throw new Error(`Template ${key} is not a string`);
  return tpl.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
}

